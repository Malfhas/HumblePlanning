import { requireAuth, requirePermission, validateBody, apiSuccess, apiError, handleApiError } from "@/lib/utils/api";
import { getAllConfig, setConfigValues, getDbConfiguredSecrets } from "@/lib/services/config-service";
import { clearLegalTextDefaults } from "@/lib/services/legal-texts";
import { isSecretKey, isPrivateConfigKey, getEnvManagedKeys, isEnvManaged, getEnvValue } from "@/lib/services/config-secrets";
import { reloadCacheSettings } from "@/lib/cache";
import { logAudit } from "@/lib/services/audit-service";
import { isAltchaConfigured } from "@/lib/altcha";
import { demoConfigOverride } from "@/lib/demo";
import { z } from "zod";

const updateConfigSchema = z.record(z.string(), z.string());

/** Stands for a secret value in the audit log (the change is recorded, never the value). */
const SECRET_AUDIT_MASK = "********";

/**
 * Computes the email sending status from the active provider and the available keys.
 * - `configured: true` if all keys required by the provider are present (env or DB)
 * - `missingKeys: []` lists the missing keys
 */
function computeEmailStatus(
  configMap: Record<string, string | null>,
  envManaged: string[],
  dbConfigured: string[],
): { configured: boolean; provider: string; missingKeys: string[] } {
  const provider = configMap.EMAIL_PROVIDER || "nuntly";
  const availableSecrets = new Set([...envManaged, ...dbConfigured]);

  const requiredByProvider: Record<string, string[]> = {
    nuntly: ["NUNTLY_API_KEY"],
    mailgun: ["MAILGUN_API_KEY"],
    smtp: ["SMTP_PASSWORD"],
  };

  const required = requiredByProvider[provider] ?? [];
  const missingKeys = required.filter((k) => !availableSecrets.has(k));

  return {
    configured: missingKeys.length === 0,
    provider,
    missingKeys,
  };
}

export async function GET() {
  try {
    await requireAuth();
    // All authenticated users can read config (needed for UI: modules, title, logo, password policy)
    // Only PUT requires settings:edit permission
    const config = await getAllConfig();
    const map: Record<string, string | null> = {};
    for (const c of config) {
      // SECURITY: never send secret values to the client, regardless of their source.
      // The UI displays "••••••" placeholder and uses _envManaged / _dbConfigured to decide behavior.
      if (isSecretKey(c.key)) continue;
      // AI chat settings (system prompt, models, quotas): dedicated admin routes.
      if (isPrivateConfigKey(c.key)) continue;
      map[c.key] = demoConfigOverride(c.key) ?? c.value;
    }
    // GDPR texts equal to their translated default: empty field (sample text displayed).
    clearLegalTextDefaults(map, "");

    const envManaged = getEnvManagedKeys();
    const dbConfigured = await getDbConfiguredSecrets();
    const emailStatus = computeEmailStatus(map, envManaged, dbConfigured);

    // Metadata serialized as JSON strings to stay compatible with
    // Record<string, string | null> consumed across the app.
    return apiSuccess({
      ...map,
      _envManaged: JSON.stringify(envManaged),
      _dbConfigured: JSON.stringify(dbConfigured),
      _emailStatus: JSON.stringify(emailStatus),
      _altchaConfigured: isAltchaConfigured() ? "true" : "false",
    });
  } catch (error) {
    return handleApiError(error);
  }
}

export async function PUT(request: Request) {
  try {
    const session = await requireAuth();
    await requirePermission(session.user.id, "settings:edit");
    const data = await validateBody(request, updateConfigSchema);
    // SECURITY: reject updates to secrets currently provided by .env — .env is authoritative.
    const envManaged = getEnvManagedKeys();
    const ignoredEnvKeys: string[] = [];
    for (const key of envManaged) {
      if (key in data) {
        ignoredEnvKeys.push(key);
        delete data[key];
      }
    }
    if (ignoredEnvKeys.length > 0) {
      console.warn(
        `[config] PUT /api/config: ignored ${ignoredEnvKeys.length} env-managed key(s): ${ignoredEnvKeys.join(", ")}`
      );
    }
    // GDPR texts equal to their default (FR or EN): nothing is saved, the
    // reader will see the default text in their language.
    clearLegalTextDefaults(data, "");
    // Snapshot current values BEFORE applying changes (for audit diff)
    const currentConfig = await getAllConfig();
    const currentMap: Record<string, string | null> = {};
    for (const c of currentConfig) currentMap[c.key] = c.value;

    // Captcha validation: if enabled with a remote provider (Turnstile /
    // reCAPTCHA), reject the save without Site/Secret keys. For ALTCHA,
    // the secrets are in .env (generated by install.sh) so nothing to
    // validate DB-side. We evaluate the effective values = merge (current ⊕ data),
    // a secret provided by .env taking precedence over the database.
    const effective = (k: string) => (k in data ? data[k] : (isEnvManaged(k) ? getEnvValue(k) : currentMap[k]) ?? "") || "";
    if (effective("CAPTCHA_ENABLED") === "true") {
      const provider = effective("CAPTCHA_PROVIDER") || "altcha";
      if (provider === "turnstile" || provider === "recaptcha") {
        const siteKey = effective("CAPTCHA_SITE_KEY").trim();
        const secretKey = effective("CAPTCHA_SECRET_KEY").trim();
        if (!siteKey || !secretKey) {
          const label = provider === "turnstile" ? "Cloudflare Turnstile" : "Google reCAPTCHA";
          return apiError("settings.errors.captchaKeysRequired", 400, undefined, { provider: label });
        }
      }
    }

    // Planning grid cell width validation: min ≤ default ≤ max, mobile_max ≥ min, all > 0.
    // The 4 settings are linked and inconsistent if entered independently.
    const numeric = (k: string, fallback: number) => {
      const raw = effective(k);
      const n = parseInt(raw, 10);
      return Number.isFinite(n) && n > 0 ? n : fallback;
    };
    const cellMin = numeric("PLANNING_MIN_CELL_WIDTH", 55);
    const cellMax = numeric("PLANNING_MAX_CELL_WIDTH", 170);
    const cellDefault = numeric("PLANNING_DEFAULT_CELL_WIDTH", 75);
    const cellMobileMax = numeric("PLANNING_MAX_CELL_WIDTH_MOBILE", 140);
    if (cellMin <= 0 || cellMax <= 0 || cellDefault <= 0 || cellMobileMax <= 0) {
      return apiError("settings.errors.cellWidthsNotPositive");
    }
    if (cellMin > cellMax) {
      return apiError("settings.errors.cellMinAboveMax");
    }
    if (cellDefault < cellMin || cellDefault > cellMax) {
      return apiError("settings.errors.cellDefaultOutOfRange");
    }
    if (cellMobileMax < cellMin) {
      return apiError("settings.errors.cellMobileBelowMin");
    }
    // Compute actual changes (skip keys whose value didn't change)
    const oldValues: Record<string, string | null> = {};
    const newValues: Record<string, string> = {};
    for (const [key, val] of Object.entries(data)) {
      const prev = currentMap[key] ?? null;
      if (prev !== val) {
        const secret = isSecretKey(key);
        oldValues[key] = secret && prev ? SECRET_AUDIT_MASK : prev;
        newValues[key] = secret && val ? SECRET_AUDIT_MASK : val;
      }
    }
    await setConfigValues(data);
    if (Object.keys(newValues).length > 0) {
      logAudit({
        userId: session.user.id,
        action: "config_change",
        entityType: "config",
        oldValues,
        newValues,
        metadata: { changedKeys: Object.keys(newValues) },
        changeCount: Object.keys(newValues).length,
      }).catch(() => {});
    }
    // Reload cache settings if cache config changed
    if (data.CACHE_ENABLED !== undefined || data.CACHE_TTL !== undefined) {
      reloadCacheSettings();
    }
    const config = await getAllConfig();
    const map: Record<string, string | null> = {};
    for (const c of config) {
      if (isSecretKey(c.key) || isPrivateConfigKey(c.key)) continue;
      map[c.key] = c.value;
    }
    clearLegalTextDefaults(map, "");
    const envManagedAfter = getEnvManagedKeys();
    const dbConfiguredAfter = await getDbConfiguredSecrets();
    const emailStatusAfter = computeEmailStatus(map, envManagedAfter, dbConfiguredAfter);
    return apiSuccess({
      ...map,
      _envManaged: JSON.stringify(envManagedAfter),
      _dbConfigured: JSON.stringify(dbConfiguredAfter),
      _emailStatus: JSON.stringify(emailStatusAfter),
    });
  } catch (error) {
    return handleApiError(error);
  }
}
