function SelectTrigger({
  className,
  size = "default",
  children,
  ...props
}: React.ComponentProps<typeof SelectPrimitive.Trigger> & {
  size?: "sm" | "default"
}) {
  return (
    <SelectPrimitive.Trigger
      data-slot="select-trigger"
      data-size={size}
      className={cn(
        // Adds `hover:bg-accent hover:text-accent-foreground` in light
        // mode to match the SelectTrigger with the outline Button (used
        // by Project / Users as a combobox) — otherwise Status
        // had no visual feedback on hover.
        "flex w-fit items-center justify-between gap-2 rounded-md border border-input bg-transparent px-3 py-2 text-sm whitespace-nowrap shadow-xs transition-[color,box-shadow] outline-none hover:bg-accent hover:text-accent-foreground focus-visible:border-ring focus-visible:ring-[3px] focus-visible:ring-ring/50 disabled:cursor-not-allowed disabled:opacity-50 aria-invalid:border-destructive aria-invalid:ring-destructive/20 data-[placeholder]:text-muted-foreground data-[size=default]:h-9 data-[size=sm]:h-8 *:data-[slot=select-value]:line-clamp-1 *:data-[slot=select-value]:flex *:data-[slot=select-value]:items-center *:data-[slot=select-value]:gap-2 dark:bg-input/30 dark:hover:bg-input/50 dark:aria-invalid:ring-destructive/40 [&_svg]:pointer-events-none [&_svg]:shrink-0 [&_svg:not([class*='size-'])]:size-4 [&_svg:not([class*='text-'])]:text-muted-foreground",
        className
      )}
      {...props}
    >
      {children}
      <SelectPrimitive.Icon asChild>
        <ChevronDownIcon className="size-4 opacity-50" />
      </SelectPrimitive.Icon>
    </SelectPrimitive.Trigger>
  )
}

function SelectContent({
  className,
  children,
  // By default, opens in "popper" mode + side="bottom": the panel
  // sits BELOW the trigger, as the user expects, and Radix collision
  // detection only shifts it when there is not enough room.
  // The former `item-aligned` default tried to align on the current item
  // and produced a broken layout on mobile (keyboard + short viewport).
  position = "popper",
  align = "start",
  side = "bottom",
  sideOffset = 4,
  avoidCollisions,
  ...props
}: React.ComponentProps<typeof SelectPrimitive.Content>) {
  // See PopoverContent: portal into DialogContent when inside
  // a Dialog, so `react-remove-scroll` does not block it.
  const portalContainer = usePortalContainer();
  // UX: opens downward by preference (`side="bottom"`), Radix may
  // shift horizontally and flip if there is really no room
  // (`avoidCollisions=true`). Prevents Selects near a viewport edge
  // from overflowing.
  const resolvedAvoidCollisions = avoidCollisions ?? true;
  return (
    <SelectPrimitive.Portal container={portalContainer ?? undefined}>
      <SelectPrimitive.Content
        data-slot="select-content"
        className={cn(
          // touch-pan-y + overscroll-contain: finger scrolling on mobile,
          // without propagating to the parent scroll (avoids the "frozen list" effect
          // on iOS when the wrapper is inside a scrollable dialog).
          "relative z-50 max-h-[min(60vh,var(--radix-select-content-available-height))] min-w-[8rem] origin-(--radix-select-content-transform-origin) overflow-x-hidden overflow-y-auto overscroll-contain touch-pan-y rounded-md border bg-popover text-popover-foreground shadow-md data-[side=bottom]:slide-in-from-top-2 data-[side=left]:slide-in-from-right-2 data-[side=right]:slide-in-from-left-2 data-[side=top]:slide-in-from-bottom-2 data-[state=closed]:animate-out data-[state=closed]:fade-out-0 data-[state=closed]:zoom-out-95 data-[state=open]:animate-in data-[state=open]:fade-in-0 data-[state=open]:zoom-in-95",
          position === "popper" &&
            "data-[side=bottom]:translate-y-1 data-[side=left]:-translate-x-1 data-[side=right]:translate-x-1 data-[side=top]:-translate-y-1",
          className
        )}
        style={{ WebkitOverflowScrolling: "touch" }}
        position={position}
        align={align}
        side={side}
        sideOffset={sideOffset}
        avoidCollisions={resolvedAvoidCollisions}
        {...props}
      >
        <SelectScrollUpButton />
        <SelectPrimitive.Viewport
          className={cn(
            "p-1",
            position === "popper" &&
              "h-[var(--radix-select-trigger-height)] w-full min-w-[var(--radix-select-trigger-width)] scroll-my-1"
          )}
        >
          {children}
        </SelectPrimitive.Viewport>
        <SelectScrollDownButton />
      </SelectPrimitive.Content>
    </SelectPrimitive.Portal>
  )
}

