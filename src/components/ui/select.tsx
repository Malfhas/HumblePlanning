"use client"

import * as React from "react"
import { CheckIcon, ChevronDownIcon, ChevronUpIcon } from "lucide-react"
import { Select as SelectPrimitive } from "radix-ui"

import { cn } from "@/lib/utils"
import { usePortalContainer } from "@/components/ui/portal-container-context"

function Select({
  autoComplete = "off",
  ...props
}: React.ComponentProps<typeof SelectPrimitive.Root> & { autoComplete?: string }) {
  // Default `autoComplete="off"` passed down to the hidden BubbleSelect that Radix
  // generates for native form submission. Without this default, Chrome warns
  // "form field has an id/name … without an autocomplete attribute" as soon
  // as a `name` is passed to the Select. Radix forwards unknown HTML props
  // to the BubbleSelect via spread (v2.x), so the hidden select does inherit
  // this attribute.
  return <SelectPrimitive.Root data-slot="select" autoComplete={autoComplete} {...props} />
}

